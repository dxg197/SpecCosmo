#include "cctk.h"

module matinv_init
  implicit none
  private
  
  public calc_syminv4
  
contains
  
  subroutine calc_syminv4 (g4, gu4)
    CCTK_REAL, intent(in)  :: g4(0:3,0:3)
    CCTK_REAL, intent(out) :: gu4(0:3,0:3)
    CCTK_REAL :: detinv
    
    ! Calculate the inverse determinant of the matrix
    detinv = &
      1/(g4(0,0)*(g4(1,1)*(g4(2,2)*g4(3,3)-g4(2,3)*g4(3,2))+g4(1,2)*(g4(2,3)*g4(3,1)-g4(2,1)*g4(3,3))+g4(1,3)*(g4(2,1)*g4(3,2)-g4(2,2)*g4(3,1)))&
       - g4(0,1)*(g4(1,0)*(g4(2,2)*g4(3,3)-g4(2,3)*g4(3,2))+g4(1,2)*(g4(2,3)*g4(3,0)-g4(2,0)*g4(3,3))+g4(1,3)*(g4(2,0)*g4(3,2)-g4(2,2)*g4(3,0)))&
       + g4(0,2)*(g4(1,0)*(g4(2,1)*g4(3,3)-g4(2,3)*g4(3,1))+g4(1,1)*(g4(2,3)*g4(3,0)-g4(2,0)*g4(3,3))+g4(1,3)*(g4(2,0)*g4(3,1)-g4(2,1)*g4(3,0)))&
       - g4(0,3)*(g4(1,0)*(g4(2,1)*g4(3,2)-g4(2,2)*g4(3,1))+g4(1,1)*(g4(2,2)*g4(3,0)-g4(2,0)*g4(3,2))+g4(1,2)*(g4(2,0)*g4(3,1)-g4(2,1)*g4(3,0))))

    ! Cg4lculg4te the inverse of the mg4trix
    gu4(0,0) = detinv*(g4(1,1)*(g4(2,2)*g4(3,3)-g4(2,3)*g4(3,2))+g4(1,2)*(g4(2,3)*g4(3,1)-g4(2,1)*g4(3,3))+g4(1,3)*(g4(2,1)*g4(3,2)-g4(2,2)*g4(3,1)))
    gu4(1,0) = detinv*(g4(1,0)*(g4(2,3)*g4(3,2)-g4(2,2)*g4(3,3))+g4(1,2)*(g4(2,0)*g4(3,3)-g4(2,3)*g4(3,0))+g4(1,3)*(g4(2,2)*g4(3,0)-g4(2,0)*g4(3,2)))
    gu4(2,0) = detinv*(g4(1,0)*(g4(2,1)*g4(3,3)-g4(2,3)*g4(3,1))+g4(1,1)*(g4(2,3)*g4(3,0)-g4(2,0)*g4(3,3))+g4(1,3)*(g4(2,0)*g4(3,1)-g4(2,1)*g4(3,0)))
    gu4(3,0) = detinv*(g4(1,0)*(g4(2,2)*g4(3,1)-g4(2,1)*g4(3,2))+g4(1,1)*(g4(2,0)*g4(3,2)-g4(2,2)*g4(3,0))+g4(1,2)*(g4(2,1)*g4(3,0)-g4(2,0)*g4(3,1)))
    gu4(0,1) = detinv*(g4(0,1)*(g4(2,3)*g4(3,2)-g4(2,2)*g4(3,3))+g4(0,2)*(g4(2,1)*g4(3,3)-g4(2,3)*g4(3,1))+g4(0,3)*(g4(2,2)*g4(3,1)-g4(2,1)*g4(3,2)))
    gu4(1,1) = detinv*(g4(0,0)*(g4(2,2)*g4(3,3)-g4(2,3)*g4(3,2))+g4(0,2)*(g4(2,3)*g4(3,0)-g4(2,0)*g4(3,3))+g4(0,3)*(g4(2,0)*g4(3,2)-g4(2,2)*g4(3,0)))
    gu4(2,1) = detinv*(g4(0,0)*(g4(2,3)*g4(3,1)-g4(2,1)*g4(3,3))+g4(0,1)*(g4(2,0)*g4(3,3)-g4(2,3)*g4(3,0))+g4(0,3)*(g4(2,1)*g4(3,0)-g4(2,0)*g4(3,1)))
    gu4(3,1) = detinv*(g4(0,0)*(g4(2,1)*g4(3,2)-g4(2,2)*g4(3,1))+g4(0,1)*(g4(2,2)*g4(3,0)-g4(2,0)*g4(3,2))+g4(0,2)*(g4(2,0)*g4(3,1)-g4(2,1)*g4(3,0)))
    gu4(0,2) = detinv*(g4(0,1)*(g4(1,2)*g4(3,3)-g4(1,3)*g4(3,2))+g4(0,2)*(g4(1,3)*g4(3,1)-g4(1,1)*g4(3,3))+g4(0,3)*(g4(1,1)*g4(3,2)-g4(1,2)*g4(3,1)))
    gu4(1,2) = detinv*(g4(0,0)*(g4(1,3)*g4(3,2)-g4(1,2)*g4(3,3))+g4(0,2)*(g4(1,0)*g4(3,3)-g4(1,3)*g4(3,0))+g4(0,3)*(g4(1,2)*g4(3,0)-g4(1,0)*g4(3,2)))
    gu4(2,2) = detinv*(g4(0,0)*(g4(1,1)*g4(3,3)-g4(1,3)*g4(3,1))+g4(0,1)*(g4(1,3)*g4(3,0)-g4(1,0)*g4(3,3))+g4(0,3)*(g4(1,0)*g4(3,1)-g4(1,1)*g4(3,0)))
    gu4(3,2) = detinv*(g4(0,0)*(g4(1,2)*g4(3,1)-g4(1,1)*g4(3,2))+g4(0,1)*(g4(1,0)*g4(3,2)-g4(1,2)*g4(3,0))+g4(0,2)*(g4(1,1)*g4(3,0)-g4(1,0)*g4(3,1)))
    gu4(0,3) = detinv*(g4(0,1)*(g4(1,3)*g4(2,2)-g4(1,2)*g4(2,3))+g4(0,2)*(g4(1,1)*g4(2,3)-g4(1,3)*g4(2,1))+g4(0,3)*(g4(1,2)*g4(2,1)-g4(1,1)*g4(2,2)))
    gu4(1,3) = detinv*(g4(0,0)*(g4(1,2)*g4(2,3)-g4(1,3)*g4(2,2))+g4(0,2)*(g4(1,3)*g4(2,0)-g4(1,0)*g4(2,3))+g4(0,3)*(g4(1,0)*g4(2,2)-g4(1,2)*g4(2,0)))
    gu4(2,3) = detinv*(g4(0,0)*(g4(1,3)*g4(2,1)-g4(1,1)*g4(2,3))+g4(0,1)*(g4(1,0)*g4(2,3)-g4(1,3)*g4(2,0))+g4(0,3)*(g4(1,1)*g4(2,0)-g4(1,0)*g4(2,1)))
    gu4(3,3) = detinv*(g4(0,0)*(g4(1,1)*g4(2,2)-g4(1,2)*g4(2,1))+g4(0,1)*(g4(1,2)*g4(2,0)-g4(1,0)*g4(2,2))+g4(0,2)*(g4(1,0)*g4(2,1)-g4(1,1)*g4(2,0)))
  end subroutine calc_syminv4
  
end module matinv_init
